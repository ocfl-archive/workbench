// IngestOCFLCmd builds the exec.Cmd for ingesting an OCFL container using ona.
// It returns the command and the target path to the result JSON file.
func IngestOCFLCmd(conf *config.WBConfig, j job.Job) (*exec.Cmd, string, error) {
	if conf == nil {
		return nil, "", fmt.Errorf("configuration cannot be nil")
	}
	ocflDir := conf.GetOcflFolder(j.Batch)
	if err := util.EnsureTargetDirectory(ocflDir); err != nil {
		return nil, "", fmt.Errorf("failed to ensure OCFL target directory '%s': %w", ocflDir, err)
	}

	zipPath := j.ExpectedZipPath(conf)
	resultJsonPath := j.ExpectedResultJsonPath(conf)

	args := []string{"ingest", "--status", resultJsonPath, "-p", zipPath}
	if conf != nil && conf.Ona.Config != "" {
		args = append(args, "-c", conf.Ona.Config)
	}

	cmd := exec.Command("ona", args...)
	return cmd, resultJsonPath, nil
}

// StatusOCFLCmd builds the exec.Cmd for querying the preservation status of an ingested package using ona.
func StatusOCFLCmd(conf *config.WBConfig, id string) (*exec.Cmd, error) {
	trimmedID := strings.TrimSpace(id)
	if trimmedID == "" {
		return nil, fmt.Errorf("cannot query status: ingest id is empty")
	}

	args := []string{"status", "-i", trimmedID}
	if conf != nil && conf.Ona.Config != "" {
		args = append(args, "-c", conf.Ona.Config)
	}

	cmd := exec.Command("ona", args...)
	return cmd, nil
}

