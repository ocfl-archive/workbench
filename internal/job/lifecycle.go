// ExtractIngestIDFile reads the result JSON file and extracts the ingest ID.
func ExtractIngestIDFile(resultJsonPath string) (string, error) {
	data, err := os.ReadFile(resultJsonPath)
	if err != nil {
		return "", fmt.Errorf("failed to read result JSON file '%s': %w", resultJsonPath, err)
	}
	id := ExtractIngestID(data)
	if id == "" {
		return "", fmt.Errorf("no valid 'id' found in result JSON file '%s'", resultJsonPath)
	}
	return id, nil
}

// CheckIngestResult reads and parses the result JSON file generated by ona ingest.
// It returns hasError=true and the error message if the file cannot be read, parsed, or if the "error" field is populated.
func CheckIngestResult(resultJsonPath string) (hasError bool, errorMsg string, err error) {
	data, err := os.ReadFile(resultJsonPath)
	if err != nil {
		return true, fmt.Sprintf("failed to read result JSON file '%s': %v", resultJsonPath, err), err
	}

	var payload map[string]interface{}
	if err := json.Unmarshal(data, &payload); err != nil {
		return true, fmt.Sprintf("failed to parse result JSON file '%s': %v", resultJsonPath, err), err
	}

	rawErr, exists := payload["error"]
	if !exists || rawErr == nil {
		return false, "", nil
	}

	switch v := rawErr.(type) {
	case string:
		trimmed := strings.TrimSpace(v)
		if trimmed != "" {
			return true, trimmed, nil
		}
		return false, "", nil
	case bool:
		if v {
			return true, "error flag is true", nil
		}
		return false, "", nil
	case map[string]interface{}:
		if len(v) > 0 {
			b, _ := json.Marshal(v)
			return true, string(b), nil
		}
		return false, "", nil
	case []interface{}:
		if len(v) > 0 {
			b, _ := json.Marshal(v)
			return true, string(b), nil
		}
		return false, "", nil
	default:
		return true, fmt.Sprintf("%v", v), nil
	}
}

// CreateUploadRecord creates a .upload.json file for the given job containing the upload timestamp.
func CreateUploadRecord(conf *config.WBConfig, j Job) error {
	ocflDir := conf.GetOcflFolder(j.Batch)
	if err := util.EnsureTargetDirectory(ocflDir); err != nil {
		return fmt.Errorf("failed to ensure OCFL target directory '%s': %w", ocflDir, err)
	}

	uploadPath := j.ExpectedUploadPath(conf)
	uploadInfo := UploadInfo{
		Date: time.Now().Format(time.RFC3339),
	}

	data, err := json.MarshalIndent(uploadInfo, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal upload record: %w", err)
	}

	if err := os.WriteFile(uploadPath, data, 0644); err != nil {
		return fmt.Errorf("failed to write upload record to '%s': %w", uploadPath, err)
	}

	return nil
}

// HandleJobError handles failure during OCFL operations by moving the incoming job directory
// and companion files to the batch's error folder, writing the execution log, and removing any partial OCFL container.
func HandleJobError(conf *config.WBConfig, j Job, cmdStr string, output string) error {
	errorDir := conf.GetErrorFolder(j.Batch)
	if err := util.EnsureTargetDirectory(errorDir); err != nil {
		return fmt.Errorf("failed to ensure error target directory '%s': %w", errorDir, err)
	}

	srcJobDir := filepath.Join(conf.GetInputFolder(j.Batch), j.BaseName)
	if j.IncomingFolder != "" {
		srcJobDir = j.IncomingFolder
	}
	dstJobDir := filepath.Join(errorDir, j.BaseName)

	if fi, err := os.Stat(srcJobDir); err == nil && fi.IsDir() {
		if err := util.MoveDirectory(srcJobDir, dstJobDir); err != nil {
			return fmt.Errorf("failed to move job directory from '%s' to '%s': %w", srcJobDir, dstJobDir, err)
		}
	}

	// Move external info JSON from input directory if present
	externalInfoJson := filepath.Join(conf.GetInputFolder(j.Batch), fmt.Sprintf("%s.json", j.BaseName))
	if fi, err := os.Stat(externalInfoJson); err == nil && !fi.IsDir() {
		dstExternalInfoJson := filepath.Join(errorDir, filepath.Base(externalInfoJson))
		if err := util.MoveFile(externalInfoJson, dstExternalInfoJson); err != nil {
			return fmt.Errorf("failed to move external info JSON '%s' to '%s': %w", externalInfoJson, dstExternalInfoJson, err)
		}
	}

	logFilePath := j.ExpectedErrorLogPath(conf)
	logContent := output
	if cmdStr != "" {
		logContent = fmt.Sprintf("%s\n\n%s", cmdStr, output)
	}
	if err := os.WriteFile(logFilePath, []byte(logContent), 0644); err != nil {
		return fmt.Errorf("failed to write error log file '%s': %w", logFilePath, err)
	}

	ocflZipPath := j.ExpectedZipPath(conf)
	if _, err := os.Stat(ocflZipPath); err == nil {
		_ = os.Remove(ocflZipPath)
	}
	if j.OcflFile != "" && j.OcflFile != ocflZipPath {
		if _, err := os.Stat(j.OcflFile); err == nil {
			_ = os.Remove(j.OcflFile)
		}
	}

	checksumCandidates := []string{
		j.ExpectedChecksumPath(conf),
		ocflZipPath + ".sha512",
	}
	if j.ChecksumFile != "" {
		checksumCandidates = append(checksumCandidates, j.ChecksumFile)
	}
	if j.OcflFile != "" {
		checksumCandidates = append(checksumCandidates, j.OcflFile+".sha512")
	}
	for _, csPath := range checksumCandidates {
		if csPath != "" {
			if _, err := os.Stat(csPath); err == nil {
				_ = os.Remove(csPath)
			}
		}
	}

	return nil
}

// HandleIngestError handles ingest failure by moving the incoming job directory to error,
// moving the result JSON file to <error>/<BaseName>_ona.json, writing the command and output to <error>/<BaseName>.log,
// and cleaning up any OCFL zip archive.
func HandleIngestError(conf *config.WBConfig, j Job, cmdStr string, output string, resultJsonPath string) error {
	if err := HandleJobError(conf, j, cmdStr, output); err != nil {
		return err
	}

	if resultJsonPath == "" {
		resultJsonPath = j.ExpectedResultJsonPath(conf)
	}

	if _, err := os.Stat(resultJsonPath); err == nil {
		errorDir := conf.GetErrorFolder(j.Batch)
		dstJsonPath := filepath.Join(errorDir, filepath.Base(resultJsonPath))
		if _, err := os.Stat(dstJsonPath); err == nil {
			_ = os.Remove(dstJsonPath)
		}
		if err := os.Rename(resultJsonPath, dstJsonPath); err != nil {
			data, readErr := os.ReadFile(resultJsonPath)
			if readErr != nil {
				return fmt.Errorf("failed to read result JSON for relocation '%s': %w", resultJsonPath, readErr)
			}
			if writeErr := os.WriteFile(dstJsonPath, data, 0644); writeErr != nil {
				return fmt.Errorf("failed to write relocated result JSON '%s': %w", dstJsonPath, writeErr)
			}
			_ = os.Remove(resultJsonPath)
		}
	}

	return nil
}

// ArchiveJob moves all job-related source files, OCFL containers, and ingest status JSON
// into the batch's archived folder upon successful ingest completion.
// Note: Validation reports in the report folder remain in place and are not relocated.
func ArchiveJob(conf *config.WBConfig, j Job, resultJsonPath string) error {
	archivedDir := conf.GetArchivedFolder(j.Batch)
	if err := util.EnsureTargetDirectory(archivedDir); err != nil {
		return fmt.Errorf("failed to ensure archived target directory '%s': %w", archivedDir, err)
	}

	// 1. Move incoming job directory to <archived>/<BaseName>
	srcJobDir := filepath.Join(conf.GetInputFolder(j.Batch), j.BaseName)
	if j.IncomingFolder != "" {
		srcJobDir = j.IncomingFolder
	}
	dstJobDir := filepath.Join(archivedDir, j.BaseName)
	if fi, err := os.Stat(srcJobDir); err == nil && fi.IsDir() {
		if err := util.MoveDirectory(srcJobDir, dstJobDir); err != nil {
			return fmt.Errorf("failed to move job directory from '%s' to '%s': %w", srcJobDir, dstJobDir, err)
		}
	}

	// 2. Move OCFL zip container to <archived>/<BaseName>.zip
	ocflZipPath := j.ExpectedZipPath(conf)
	if j.OcflFile != "" {
		ocflZipPath = j.OcflFile
	}
	if fi, err := os.Stat(ocflZipPath); err == nil && !fi.IsDir() {
		dstZipPath := filepath.Join(archivedDir, filepath.Base(ocflZipPath))
		if err := util.MoveFile(ocflZipPath, dstZipPath); err != nil {
			return fmt.Errorf("failed to move OCFL zip '%s' to '%s': %w", ocflZipPath, dstZipPath, err)
		}
	}

	// 2b. Move OCFL checksum file (.sha512) to <archived>
	var checksumCandidates []string
	if j.ChecksumFile != "" {
		checksumCandidates = append(checksumCandidates, j.ChecksumFile)
	}
	if expectedCs := j.ExpectedChecksumPath(conf); expectedCs != "" {
		checksumCandidates = append(checksumCandidates, expectedCs)
	}
	if ocflZipPath != "" {
		checksumCandidates = append(checksumCandidates, ocflZipPath+".sha512")
	}
	for _, csPath := range checksumCandidates {
		if fi, err := os.Stat(csPath); err == nil && !fi.IsDir() {
			dstChecksumPath := filepath.Join(archivedDir, filepath.Base(csPath))
			if err := util.MoveFile(csPath, dstChecksumPath); err != nil {
				return fmt.Errorf("failed to move OCFL checksum '%s' to '%s': %w", csPath, dstChecksumPath, err)
			}
			break
		}
	}

	// 3. Move result / status JSON to <archived>/<BaseName>_ona.json
	if resultJsonPath == "" {
		resultJsonPath = j.ExpectedResultJsonPath(conf)
	}
	if fi, err := os.Stat(resultJsonPath); err == nil && !fi.IsDir() {
		dstJsonPath := filepath.Join(archivedDir, filepath.Base(resultJsonPath))
		if err := util.MoveFile(resultJsonPath, dstJsonPath); err != nil {
			return fmt.Errorf("failed to move status JSON '%s' to '%s': %w", resultJsonPath, dstJsonPath, err)
		}
	}

	// 4. Move upload marker if present
	uploadPath := j.ExpectedUploadPath(conf)
	if j.UploadFile != "" && j.UploadFile != resultJsonPath {
		uploadPath = j.UploadFile
	}
	if fi, err := os.Stat(uploadPath); err == nil && !fi.IsDir() {
		dstUploadPath := filepath.Join(archivedDir, filepath.Base(uploadPath))
		if err := util.MoveFile(uploadPath, dstUploadPath); err != nil {
			return fmt.Errorf("failed to move upload JSON '%s' to '%s': %w", uploadPath, dstUploadPath, err)
		}
	}

	// 5. Move external info JSON from input directory if present
	externalInfoJson := filepath.Join(conf.GetInputFolder(j.Batch), fmt.Sprintf("%s.json", j.BaseName))
	if fi, err := os.Stat(externalInfoJson); err == nil && !fi.IsDir() {
		dstExternalInfoJson := filepath.Join(archivedDir, filepath.Base(externalInfoJson))
		if err := util.MoveFile(externalInfoJson, dstExternalInfoJson); err != nil {
			return fmt.Errorf("failed to move external info JSON '%s' to '%s': %w", externalInfoJson, dstExternalInfoJson, err)
		}
	}

	return nil
}
